// Writes app/theme/fb-specialist-assets.js from
// concept-design/F-B-final/asset-manifest.json (docs/ui/08_fb_specialist_visual.md §1:
// the only mapping source). Taro bundles images through static imports, so the
// table is generated, never edited by hand; test/fb-specialist.test.js fails when
// it is out of date with the manifest.
//
//   node scripts/sync-fb-assets.mjs           # write
//   node scripts/sync-fb-assets.mjs --check   # exit 1 when stale
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const REPO = fileURLToPath(new URL("..", import.meta.url));
export const FB_DIR = "concept-design/F-B-final";
export const FB_MANIFEST = `${FB_DIR}/asset-manifest.json`;
export const OUT = "app/theme/fb-specialist-assets.js";
/**
 * Which manifest file a client loads. Domains: `asset` (256px; 56px display is
 * already ≥ 4× on every phone). Mascot: `asset_2x`, the 512px file — in this
 * manifest `asset` is the 1024px master (844 KB), too heavy for the Mini Program
 * package for an 80px header picture.
 */
export const DOMAIN_KEY = "asset";
export const MASCOT_KEY = "asset_2x";

export function fbTable(manifest) {
  const lines = [];
  const entries = [];
  const ident = (s) => s.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""));
  for (const [domain, d] of Object.entries(manifest.domains)) {
    const name = `domain${ident(`_${domain}`)}`;
    lines.push(`import ${name} from "../../${FB_DIR}/${d[DOMAIN_KEY]}";`);
    entries.push(`  "domain.${domain}": { src: ${name}, manifestKey: "domains.${domain}.${DOMAIN_KEY}", group: "${d.group}" },`);
  }
  lines.push(`import specialistMascot from "../../${FB_DIR}/${manifest.mascot[MASCOT_KEY]}";`);
  entries.push(`  "specialist.mascot": { src: specialistMascot, manifestKey: "mascot.${MASCOT_KEY}" },`);
  return `/**
 * GENERATED by scripts/sync-fb-assets.mjs from ${FB_MANIFEST}. Do not edit.
 *
 * The F-B specialist page's pictures (docs/ui/08_fb_specialist_visual.md): one
 * transparent PNG per \`domain.<domain_id>\` slot and the header mascot (the
 * existing welcome pose, reused). H5 and the Mini Program load the same files;
 * only the bundler's output path differs. Components ask for a slot, never a file.
 */
${lines.join("\n")}

export const fbSpecialistAssets = Object.freeze({
${entries.join("\n")}
});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const manifest = JSON.parse(readFileSync(`${REPO}/${FB_MANIFEST}`, "utf8"));
  const text = fbTable(manifest);
  if (process.argv.includes("--check")) {
    const ok = readFileSync(`${REPO}/${OUT}`, "utf8") === text;
    console.log(ok ? `${OUT} matches ${FB_MANIFEST}` : `${OUT} is stale: run node scripts/sync-fb-assets.mjs`);
    process.exit(ok ? 0 : 1);
  }
  writeFileSync(`${REPO}/${OUT}`, text);
  console.log(`wrote ${OUT}`);
}
